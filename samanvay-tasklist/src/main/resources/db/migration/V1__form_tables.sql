-- Application-owned form configuration (TRD section 5.1).
-- Kept separate from the engine's ACT_* tables.

create table form_definition (
    id            bigint generated by default as identity primary key,
    form_key      varchar(255)             not null,
    name          varchar(255)             not null,
    description   varchar(2000),
    status        varchar(32)              not null,
    draft_schema_json    text,
    draft_ui_schema_json text,
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null,
    constraint uq_form_definition_key unique (form_key)
);

-- Published versions are immutable; editing creates a new version.
create table form_version (
    id                 bigint generated by default as identity primary key,
    form_definition_id bigint                   not null references form_definition (id),
    version            integer                  not null,
    schema_json        text                     not null,
    ui_schema_json     text,
    published_at       timestamp with time zone not null,
    published_by       varchar(255)             not null,
    constraint uq_form_version unique (form_definition_id, version)
);

create table form_binding (
    id                     bigint generated by default as identity primary key,
    form_definition_id     bigint       not null references form_definition (id),
    task_definition_key    varchar(255) not null,
    process_definition_key varchar(255),
    priority               integer      not null default 0
);

create index idx_form_binding_task on form_binding (task_definition_key);

create table form_audit_event (
    id                 bigint generated by default as identity primary key,
    form_definition_id bigint                   not null references form_definition (id),
    form_version_id    bigint references form_version (id),
    action             varchar(64)              not null,
    actor              varchar(255)             not null,
    occurred_at        timestamp with time zone not null,
    correlation_id     varchar(64)
);
